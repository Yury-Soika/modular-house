import type { Field, GlobalConfig } from "payload";
import { authenticated, anyone } from "./access";

type PageDefaults = {
  slug: string;
  label: string;
  path: string;
  title: string;
  description: string;
  eyebrow: string;
  lead: string;
  introTitle: string;
  paragraphs: string[];
  sections: { title: string; text: string; items?: string[] }[];
  ctaTitle: string;
  ctaText: string;
  showContacts?: boolean;
};

type CategoryDefaults = {
  slug: string;
  label: string;
  path: string;
  kind: "house" | "bath";
  metaTitle: string;
  title: string;
  description: string;
  eyebrow: string;
  lead: string;
  introTitle: string;
  paragraphs: string[];
  benefits: string[];
  catalogTitle: string;
};

const seoFields = (defaults: { title: string; description: string }): Field[] => [
  { name: "metaTitle", label: "SEO-заголовок", type: "text", required: true, defaultValue: defaults.title },
  { name: "metaDescription", label: "SEO-описание", type: "textarea", required: true, defaultValue: defaults.description },
  { name: "ogImage", label: "Изображение для соцсетей", type: "upload", relationTo: "media" }
];

const listField = (name: string, label: string, values: string[]): Field => ({
  name,
  label,
  type: "array",
  defaultValue: values.map((text) => ({ text })),
  fields: [{ name: "text", label: "Текст", type: "textarea", required: true }]
});

const baseGlobal = (slug: string, label: string): Pick<GlobalConfig, "slug" | "label" | "admin" | "access" | "versions"> => ({
  slug,
  label,
  admin: { group: "Страницы" },
  access: { read: anyone, update: authenticated },
  versions: { drafts: true }
});

export const infoPageGlobal = (defaults: PageDefaults): GlobalConfig => ({
  ...baseGlobal(defaults.slug, defaults.label),
  admin: { group: "Страницы", preview: () => defaults.path, livePreview: { url: () => defaults.path } },
  fields: [
    { name: "seo", label: "SEO", type: "group", fields: seoFields(defaults) },
    { name: "eyebrow", label: "Название раздела", type: "text", required: true, defaultValue: defaults.eyebrow },
    { name: "title", label: "Заголовок страницы", type: "text", required: true, defaultValue: defaults.title.replace(" | Modul S", "") },
    { name: "lead", label: "Вводный текст", type: "textarea", required: true, defaultValue: defaults.lead },
    { name: "introTitle", label: "Заголовок введения", type: "text", required: true, defaultValue: defaults.introTitle },
    listField("paragraphs", "Абзацы введения", defaults.paragraphs),
    {
      name: "sections",
      label: "Карточки разделов",
      type: "array",
      defaultValue: defaults.sections.map((section) => ({
        title: section.title,
        text: section.text,
        items: section.items?.map((text) => ({ text }))
      })),
      fields: [
        { name: "title", label: "Заголовок", type: "text", required: true },
        { name: "text", label: "Текст", type: "textarea", required: true },
        listField("items", "Пункты", [])
      ]
    },
    { name: "ctaTitle", label: "Заголовок призыва", type: "text", required: true, defaultValue: defaults.ctaTitle },
    { name: "ctaText", label: "Текст призыва", type: "textarea", required: true, defaultValue: defaults.ctaText },
    { name: "showContacts", label: "Показывать контактные карточки", type: "checkbox", defaultValue: defaults.showContacts ?? false }
  ]
});

